import { Note } from 'tonal'
import type { Selection } from './types.js'
import type { ScaleSelection } from './harmony.js'
import { selectionDegrees } from './fretboard.js'
import { ROOTS } from './roots.js'

export type CircleKey = {
  /** Clockwise position, C at 0. */
  index: number
  /** Primary major-key spelling: fewest accidentals ("Db", not "C#"). */
  major: string
  /** Enharmonic major spelling where one is selectable ("Gb" for "F#"). */
  majorAlt: string | null
  /** Relative minor of the primary spelling. */
  minor: string
  minorAlt: string | null
  /** Key signature of the primary spelling: sharps > 0, flats < 0. */
  sharps: number
}

/** Transpose C by a run of perfect fifths (negative = downward). */
function byFifths(steps: number): string {
  let note = 'C'
  const interval = steps >= 0 ? '5P' : '-5P'
  for (let i = 0; i < Math.abs(steps); i++) {
    note = Note.pitchClass(Note.transpose(note, interval))
  }
  return note
}

const relativeMinor = (major: string): string => Note.pitchClass(Note.transpose(major, '6M'))

const selectable = (note: string): string | null =>
  ROOTS.some(r => r.root === note) ? note : null

/**
 * The circle of fifths: 12 keys clockwise from C, each a fifth up from the
 * last. Spellings are generated by fifth-stacking on the key signature's own
 * side of the circle, so the flat keys come out as Db/Ab/Eb, never C#/G#/D#;
 * the boundary keys carry their selectable enharmonic twin (F#/Gb, Db/C#).
 */
export const CIRCLE_OF_FIFTHS: CircleKey[] = Array.from({ length: 12 }, (_, index) => {
  const sharps = index <= 6 ? index : index - 12
  const major = byFifths(sharps >= 0 ? index : index - 12)
  const altSteps = sharps >= 0 ? index - 12 : index
  const majorAlt = Math.abs(altSteps) <= 7 ? selectable(byFifths(altSteps)) : null
  return {
    index,
    major,
    majorAlt,
    minor: relativeMinor(major),
    minorAlt: majorAlt ? selectable(relativeMinor(majorAlt)) : null,
    sharps,
  }
})

export type CirclePosition = {
  index: number
  /** Which ring the selection's root lives on, by the selection's third. */
  ring: 'major' | 'minor'
}

/**
 * Where a selection sits on the circle. The ring follows the selection's
 * quality — a major third puts the root on the outer (major) ring, a minor
 * third without one on the inner (relative-minor) ring; selections with
 * neither third (a power chord) default to the major ring.
 */
export function circlePosition(selection: Selection): CirclePosition {
  const chroma = Note.chroma(selection.root)
  if (chroma === undefined) throw new Error(`bad root: ${selection.root}`)
  const semis = new Set(selectionDegrees(selection).map(d => d.semitones % 12))
  const ring = semis.has(4) ? 'major' : semis.has(3) ? 'minor' : 'major'
  const index = CIRCLE_OF_FIFTHS.findIndex(
    k => Note.chroma(ring === 'major' ? k.major : k.minor) === chroma,
  )
  return { index, ring }
}

export type CircleDiatonic = {
  /** The key's major triad lives inside the scale. */
  major: boolean
  /** The key's relative-minor triad lives inside the scale. */
  minor: boolean
}

/**
 * Which circle keys' triads are diatonic to a scale, by pitch-class
 * containment — for a major key this lights the classic contiguous
 * neighborhood: the key, its dominant, and its subdominant on both rings.
 */
export function diatonicOnCircle(scale: ScaleSelection): CircleDiatonic[] {
  if (scale.mode !== 'scale') throw new Error('diatonicOnCircle needs a scale selection')
  const rootChroma = Note.chroma(scale.root)
  if (rootChroma === undefined) throw new Error(`bad root: ${scale.root}`)
  const chromas = new Set(selectionDegrees(scale).map(d => (rootChroma + d.semitones) % 12))
  const hasTriad = (root: string, minorThird: boolean): boolean => {
    const c = Note.chroma(root)!
    return [0, minorThird ? 3 : 4, 7].every(s => chromas.has((c + s) % 12))
  }
  return CIRCLE_OF_FIFTHS.map(k => ({
    major: hasTriad(k.major, false),
    minor: hasTriad(k.minor, true),
  }))
}
